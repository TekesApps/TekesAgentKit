//! Public annotation DTOs. The same declarations generate the TypeScript binding.
use crate::{ArtifactSelectionReference, Result, require};
use serde::{Deserialize, Serialize};

macro_rules! binding {
    ($(#[$struct_attr:meta])* $name:ident, $typescript:ident, {$($(#[$attr:meta])* $field:ident: $rust:ty => $json:literal: $ts:literal),* $(,)?}) => {
        $(#[$struct_attr])*
        #[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
        #[serde(rename_all = "camelCase")]
        pub struct $name { $($(#[$attr])* pub $field: $rust),* }
        pub const $typescript: &str = concat!("export interface ", stringify!($name), " {\n", $("  ", $json, ": ", $ts, ";\n",)* "}\n");
    }
}
pub(crate) use binding;
binding!(TranscriptAnnotationSource, SOURCE_TYPESCRIPT, {
    endpoint: String => "endpoint": "string",
    session_id: String => "sessionId": "string",
    item_id: String => "itemId": "string",
    turn_id: String => "turnId": "string",
    kind: String => "kind": "'user' | 'assistant' | 'narration'",
    start: usize => "start": "number",
    end: usize => "end": "number",
    fingerprint: String => "fingerprint": "string",
});
binding!(ComposerAnnotation, ANNOTATION_TYPESCRIPT, {
    id: String => "id": "string",
    source: String => "source": "string",
    excerpt: String => "excerpt": "string",
    comment: String => "comment": "string",
    #[serde(default, skip_serializing_if = "Option::is_none")]
    source_locator: Option<TranscriptAnnotationSource> => "sourceLocator?": "TranscriptAnnotationSource",
    #[serde(default, skip_serializing_if = "Option::is_none")]
    artifact_reference: Option<Box<ArtifactSelectionReference>> => "artifactReference?": "ArtifactSelectionReference",
});
binding!(AnnotationInput, INPUT_TYPESCRIPT, {
    text: String => "text": "string",
    #[serde(default)]
    annotations: Vec<ComposerAnnotation> => "annotations": "ComposerAnnotation[]",
});
binding!(AnnotationInputPresentation, PRESENTATION_TYPESCRIPT, {
    text: String => "text": "string",
    annotations: Vec<ComposerAnnotation> => "annotations": "ComposerAnnotation[]",
});
binding!(AnnotationCompilation, COMPILATION_TYPESCRIPT, {
    text: String => "text": "string",
});

pub const ANNOTATION_LIMIT: usize = 50;
impl ComposerAnnotation {
    pub fn validate(&self) -> Result<()> {
        require(
            !self.id.is_empty() && self.id.len() <= 1024,
            "invalid annotation id",
        )?;
        require(
            !self.source.is_empty() && self.source.len() <= 16_384,
            "invalid annotation source",
        )?;
        require(
            !self.excerpt.trim().is_empty()
                && self.excerpt.encode_utf16().count() <= 100_000
                && self.comment.encode_utf16().count() <= 100_000,
            "invalid annotation text",
        )?;
        if let Some(s) = &self.source_locator {
            require(
                [
                    &s.endpoint,
                    &s.session_id,
                    &s.item_id,
                    &s.turn_id,
                    &s.fingerprint,
                ]
                .iter()
                .all(|v| !v.is_empty() && v.len() <= 16_384),
                "invalid annotation locator",
            )?;
            require(
                matches!(s.kind.as_str(), "user" | "assistant" | "narration")
                    && s.start < s.end
                    && s.end <= 9_007_199_254_740_991
                    && s.end - s.start == self.excerpt.encode_utf16().count(),
                "invalid annotation range",
            )?;
        }
        if let Some(reference) = &self.artifact_reference {
            reference.validate()?;
            require(
                reference.quote == self.excerpt,
                "artifact selection quote differs from annotation excerpt",
            )?;
        }
        Ok(())
    }
}
pub fn annotation_typescript() -> String {
    format!(
        "// Generated by tekes-agent-contract; do not edit.\nexport declare const annotationContractVersion: 1;\nexport declare const annotationLimit: {ANNOTATION_LIMIT};\n{}{}{}{}{}{}",
        SOURCE_TYPESCRIPT,
        crate::ARTIFACT_SELECTION_TYPESCRIPT,
        ANNOTATION_TYPESCRIPT,
        INPUT_TYPESCRIPT,
        PRESENTATION_TYPESCRIPT,
        COMPILATION_TYPESCRIPT
    )
}
#[cfg(test)]
mod tests {
    use super::*;
    use crate::Utf16SelectionRange;

    #[test]
    fn artifact_reference_is_optional_backward_compatible_and_quote_bound() {
        let legacy = serde_json::json!({
            "id":"legacy", "source":"reply", "excerpt":"中文", "comment":"why"
        });
        let decoded: ComposerAnnotation = serde_json::from_value(legacy).unwrap();
        assert!(decoded.artifact_reference.is_none());
        assert!(decoded.source_locator.is_none());
        assert!(decoded.validate().is_ok());
        let encoded = serde_json::to_value(&decoded).unwrap();
        assert!(encoded.get("artifactReference").is_none());

        let reference = ArtifactSelectionReference::capture(
            "doc".into(),
            "artifact".into(),
            "character".into(),
            vec!["field".into()],
            "rev-1".into(),
            "sha256:test".into(),
            "中文🐉",
            Utf16SelectionRange {
                location: 0,
                length: "中文🐉".encode_utf16().count() as u64,
            },
            0,
            0,
        )
        .unwrap();
        let typed = ComposerAnnotation {
            id: "typed".into(),
            source: "document".into(),
            excerpt: "中文🐉".into(),
            comment: "why".into(),
            source_locator: None,
            artifact_reference: Some(Box::new(reference.clone())),
        };
        typed.validate().unwrap();
        let restored: ComposerAnnotation =
            serde_json::from_value(serde_json::to_value(&typed).unwrap()).unwrap();
        assert_eq!(restored.artifact_reference.as_deref(), Some(&reference));
        let mut wrong_quote = restored;
        wrong_quote.excerpt = "别的引用".into();
        assert!(wrong_quote.validate().is_err());
    }

    #[test]
    fn published_typescript_matches_rust_contract() {
        assert_eq!(
            format!(
                "{}{}{}{}",
                super::annotation_typescript(),
                crate::thread_actions_typescript(),
                crate::live_usage_typescript(),
                crate::permissions_typescript()
            ),
            include_str!("../../../web-contract/index.d.ts")
        );
    }
}
