//! Public annotation DTOs. The same declarations generate the TypeScript binding.
use crate::{Result, require};
use serde::{Deserialize, Serialize};

macro_rules! binding {
    ($(#[$struct_attr:meta])* $name:ident, $typescript:ident, {$($(#[$attr:meta])* $field:ident: $rust:ty => $json:literal: $ts:literal),* $(,)?}) => {
        $(#[$struct_attr])*
        #[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
        #[serde(rename_all = "camelCase")]
        pub struct $name { $($(#[$attr])* pub $field: $rust),* }
        pub const $typescript: &str = concat!("export interface ", stringify!($name), " {\n", $("  ", $json, ": ", $ts, ";\n",)* "}\n");
    }
}
pub(crate) use binding;
binding!(TranscriptAnnotationSource, SOURCE_TYPESCRIPT, {
    endpoint: String => "endpoint": "string",
    session_id: String => "sessionId": "string",
    item_id: String => "itemId": "string",
    turn_id: String => "turnId": "string",
    kind: String => "kind": "'user' | 'assistant' | 'narration'",
    start: usize => "start": "number",
    end: usize => "end": "number",
    fingerprint: String => "fingerprint": "string",
});
binding!(ComposerAnnotation, ANNOTATION_TYPESCRIPT, {
    id: String => "id": "string",
    source: String => "source": "string",
    excerpt: String => "excerpt": "string",
    comment: String => "comment": "string",
    #[serde(default, skip_serializing_if = "Option::is_none")]
    source_locator: Option<TranscriptAnnotationSource> => "sourceLocator?": "TranscriptAnnotationSource",
});
binding!(AnnotationInput, INPUT_TYPESCRIPT, {
    text: String => "text": "string",
    #[serde(default)]
    annotations: Vec<ComposerAnnotation> => "annotations": "ComposerAnnotation[]",
});
binding!(AnnotationInputPresentation, PRESENTATION_TYPESCRIPT, {
    text: String => "text": "string",
    annotations: Vec<ComposerAnnotation> => "annotations": "ComposerAnnotation[]",
});
binding!(AnnotationCompilation, COMPILATION_TYPESCRIPT, {
    text: String => "text": "string",
});

pub const ANNOTATION_LIMIT: usize = 50;
impl ComposerAnnotation {
    pub fn validate(&self) -> Result<()> {
        require(
            !self.id.is_empty() && self.id.len() <= 1024,
            "invalid annotation id",
        )?;
        require(
            !self.source.is_empty() && self.source.len() <= 16_384,
            "invalid annotation source",
        )?;
        require(
            !self.excerpt.trim().is_empty()
                && self.excerpt.encode_utf16().count() <= 100_000
                && self.comment.encode_utf16().count() <= 100_000,
            "invalid annotation text",
        )?;
        if let Some(s) = &self.source_locator {
            require(
                [
                    &s.endpoint,
                    &s.session_id,
                    &s.item_id,
                    &s.turn_id,
                    &s.fingerprint,
                ]
                .iter()
                .all(|v| !v.is_empty() && v.len() <= 16_384),
                "invalid annotation locator",
            )?;
            require(
                matches!(s.kind.as_str(), "user" | "assistant" | "narration")
                    && s.start < s.end
                    && s.end <= 9_007_199_254_740_991
                    && s.end - s.start == self.excerpt.encode_utf16().count(),
                "invalid annotation range",
            )?;
        }
        Ok(())
    }
}
pub fn annotation_typescript() -> String {
    format!(
        "// Generated by tekes-agent-contract; do not edit.\nexport declare const annotationContractVersion: 1;\nexport declare const annotationLimit: {ANNOTATION_LIMIT};\n{}{}{}{}{}",
        SOURCE_TYPESCRIPT,
        ANNOTATION_TYPESCRIPT,
        INPUT_TYPESCRIPT,
        PRESENTATION_TYPESCRIPT,
        COMPILATION_TYPESCRIPT
    )
}
