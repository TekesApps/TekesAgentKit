fn main() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../web-contract");
    std::fs::write(
        root.join("index.d.ts"),
        format!(
            "{}{}{}",
            tekes_agent_contract::annotation_typescript(),
            tekes_agent_contract::thread_actions_typescript(),
            tekes_agent_contract::live_usage_typescript()
        ),
    )
    .unwrap();
    std::fs::write(root.join("index.js"), format!("// Generated by tekes-agent-contract; do not edit.\nexport const annotationContractVersion = 1;\nexport const annotationLimit = {};\n", tekes_agent_contract::ANNOTATION_LIMIT)).unwrap();
}
